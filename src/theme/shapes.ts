/**
 * A small library of Material 3 Expressive shapes — the cookies, clovers,
 * bursts and suns M3 uses for avatars, icon containers and decoration — as
 * CSS `polygon()` values, so any element can take one with `clip-path`.
 *
 * Each shape is a closed curve in polar form, sampled densely enough that
 * the polygon reads as a curve at any size this theme renders it, then
 * scaled to fill its box. `styles/shapes.css` is generated from this file by
 * `scripts/generate-shapes.ts`; a test fails if the two drift apart.
 */

type Radius = (theta: number) => number;

/** A circle with `lobes` soft scallops of relative `depth` — cookies, suns, flowers. */
const scalloped =
  (lobes: number, depth: number): Radius =>
  (theta) =>
    1 + depth * Math.cos(lobes * theta);

/** Gielis' superformula: rounded polygons (pentagon, gem) and squircles. */
const superformula =
  (m: number, n1: number, n2: number, n3: number): Radius =>
  (theta) => {
    const t = (m * theta) / 4;
    return (Math.abs(Math.cos(t)) ** n2 + Math.abs(Math.sin(t)) ** n3) ** (-1 / n1);
  };

export const SHAPES = {
  circle: () => 1,
  square: superformula(4, 6, 6, 6),
  pentagon: superformula(5, 9, 9, 9),
  gem: superformula(6, 9, 9, 9),
  sunny: scalloped(8, 0.06),
  "very-sunny": scalloped(8, 0.13),
  "cookie-4": scalloped(4, 0.1),
  "cookie-6": scalloped(6, 0.08),
  "cookie-7": scalloped(7, 0.075),
  "cookie-9": scalloped(9, 0.065),
  "cookie-12": scalloped(12, 0.05),
  "clover-4": scalloped(4, 0.24),
  "clover-8": scalloped(8, 0.16),
  "soft-burst": scalloped(10, 0.1),
  flower: scalloped(6, 0.2),
} satisfies Record<string, Radius>;

export type ShapeName = keyof typeof SHAPES;

export const SHAPE_NAMES = Object.keys(SHAPES) as ShapeName[];

/** The shape as a CSS `polygon()` that fills a square box. */
export function shapePolygon(name: ShapeName, samples = 192): string {
  const radius: Radius = SHAPES[name];
  // Start at the top so lobed shapes sit symmetrically.
  const points = Array.from({ length: samples }, (_, i) => {
    const theta = (i / samples) * 2 * Math.PI - Math.PI / 2;
    const r = radius(theta);
    return [r * Math.cos(theta), r * Math.sin(theta)] as const;
  });
  const extent = Math.max(...points.flatMap(([x, y]) => [Math.abs(x), Math.abs(y)]));
  // 0.1% steps are under a pixel at any size the theme draws a shape.
  const pct = (v: number) => `${Number((50 + (v / extent) * 50).toFixed(1))}%`;
  return `polygon(${points.map(([x, y]) => `${pct(x)} ${pct(y)}`).join(",")})`;
}

/** The generated stylesheet: one `--md3-shape-<name>` custom property per shape. */
export function shapesCss(): string {
  const decls = SHAPE_NAMES.map((name) => `  --md3-shape-${name}: ${shapePolygon(name)};`);
  return [
    "/* Generated by scripts/generate-shapes.ts from src/theme/shapes.ts. Do not edit. */",
    ":root {",
    ...decls,
    "}",
    "",
  ].join("\n");
}
